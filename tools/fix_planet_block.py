# -*- coding: utf-8 -*-
"""Приводит блок данных о планете к виду официального перевода третьей части
и заодно исправляет склейки, если предыдущий проход их наделал.

Высота орбиты: 1,4 АЕ
Период обращения (в земных годах): 1,4
Радиус: 6 302 км
Продолжительность суток: 40,1 земных часов
Атмосферное давление: 0,34 земных атмосфер
Температура на поверхности: -30 °C
Сила тяжести: 0,66 G
"""
import json, io, glob, re, sys
sys.stdout.reconfigure(encoding='utf-8')

LABELS = ['Высота орбиты', 'Расстояние до звезды', 'Период обращения', 'Радиус',
          'Продолжительность суток', 'Атмосферное давление', 'Температура на поверхности',
          'Температура поверхности', 'Сила тяжести', 'Население', 'Спутники', 'Столица',
          'Основание колонии', 'Колония основана', 'Кеплеровское отношение']

NUM = r'-?[\d][\d  ,.]*?'


def fix(t):
    # 1) расклеить слипшиеся подписи
    for lab in LABELS:
        t = re.sub(r'(?<=[\d%A-Za-zА-Яа-я])(' + lab + r':)', r'\n\1', t)
    out = []
    for line in t.split('\n'):
        s = line
        s = re.sub(r'^\s*Расстояние до звезды:\s*', 'Высота орбиты: ', s)
        s = re.sub(r'^(\s*)Высота орбиты:\s*(' + NUM + r')\s*(?:а\.е\.|АЕ|a\.e\.|AU)\s*$',
                   r'\1Высота орбиты: \2 АЕ', s)
        s = re.sub(r'^(\s*)Период обращения(?: \(в земных годах\))?:\s*(' + NUM +
                   r')\s*(?:земн\w*\s*(?:год\w*|лет))?\s*$',
                   r'\1Период обращения (в земных годах): \2', s)
        s = re.sub(r'^(\s*)Продолжительность суток:\s*(' + NUM + r')\s*земн\w*\s*час\w*\s*$',
                   r'\1Продолжительность суток: \2 земных часов', s)
        s = re.sub(r'^(\s*)Атмосферное давление:\s*(' + NUM + r')\s*земн\w*\s*атмосфер\w*\s*$',
                   r'\1Атмосферное давление: \2 земных атмосфер', s)
        s = re.sub(r'^(\s*)Температура поверхности:', r'\1Температура на поверхности:', s)
        s = re.sub(r'^(\s*)(Температура на поверхности:\s*' + NUM +
                   r')\s*(?:°\s*C|C\b|градус\w*\s*Цельсия|по Цельсию)\s*$', r'\1\2 °C', s)
        s = re.sub(r'^(\s*)(Сила тяжести:\s*' + NUM + r')\s*[gG]\s*$', r'\1\2 G', s)
        s = re.sub(r'^(\s*)(Радиус:\s*' + NUM + r')\s*км\s*$', r'\1\2 км', s)
        s = re.sub(r'(:\s*' + NUM + r')\s\s+(АЕ|км|земных|°C|G)', r'\1 \2', s)
        s = re.sub(r'\s+$', '', s) if re.search(r'(' + '|'.join(LABELS) + r'):', s) else s
        out.append(s)
    return '\n'.join(out)


n = 0
for p in sorted(glob.glob('translation/*.json')):
    d = json.load(io.open(p, encoding='utf-8'))
    ch = False
    for k, v in list(d.items()):
        if not isinstance(v, str):
            continue
        nv = fix(v)
        if nv != v:
            d[k] = nv
            ch = True
            n += 1
    if ch:
        json.dump(d, io.open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('исправлено строк:', n)
