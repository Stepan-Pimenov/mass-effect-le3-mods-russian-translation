def main():
    # текущий женский перевод по стемам
    cur = {}
    for p in sorted(glob.glob(os.path.join(ROOT, 'translation', '*.json'))):
        stem = os.path.basename(p).split('.')[0]
        d = json.load(io.open(p, encoding='utf-8'))
        if isinstance(d, dict):
            for k, v in d.items():
                if isinstance(v, str):
                    cur.setdefault(stem, {})[k] = v

    outdir = os.path.join(ROOT, 'translation_male')
    os.makedirs(outdir, exist_ok=True)
    total = 0
    problems = []
    for stem, ids in sorted(R.items()):
        out = {}
        for sid, pairs in sorted(ids.items()):
            src = cur.get(stem, {}).get(sid)
            if src is None:
                problems.append('%s %s: нет такой строки' % (stem, sid)); continue
            v = src
            for a, b in pairs:
                if a not in v:
                    problems.append('%s %s: не найдено %r' % (stem, sid, a))
                v = v.replace(a, b)
            if v != src:
                out[sid] = v; total += 1
        if out:
            io.open(os.path.join(outdir, stem + '.json'), 'w', encoding='utf-8').write(
                json.dumps(out, ensure_ascii=False, indent=1))
            print('%-28s %3d строк' % (stem, len(out)))
    print('всего строк в мужском варианте:', total)
    for p in problems:
        print('  !', p)


if __name__ == '__main__':
    main()
